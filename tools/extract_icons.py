# Packs the game's Special Items icons into source/ui/item_icons.inc (a 256x128 RGBA8 atlas, 8 icons
# of 32x32 per row, in the menu's slot order).
#
# The icons are 32x32 CI4 textures on a sheet the menu loads at RAM 0x802A9300 only while it's open;
# the renderer's texture dump (snapshots_full.txt) writes each one decoded with its palette as
# tex_<source>_32x32_*.rgba. The source addresses per slot come from the menu's draw list with every
# item owned (pokes on the item flags), see SLOT_SOURCES.
# Run: python -I tools/extract_icons.py <snap_N directory>
import glob
import os
import sys

ROOT = __file__.replace("\\", "/").rsplit("/tools/", 1)[0]
DUMP = sys.argv[1]

# Grid slot -> icon source address (Special Items screen, left to right, top to bottom).
SLOT_SOURCES = [0x2AB320, 0x2A9300, 0x2A9310, 0x2A9320, 0x2A9360, 0x2A9330,
                0x2AA330, 0x2AA340, 0x2AA350, 0x2A9370, 0x2AA310, 0x2AA320,
                0x2AB330, 0x2AA300, 0x2AA360, 0x2AA370, 0x2AB300, 0x2AB310]

W, H = 256, 128
atlas = [0] * (W * H)
for slot, src in enumerate(SLOT_SOURCES):
    files = glob.glob(os.path.join(DUMP, "tex_%06X_32x32_*.rgba" % src))
    if not files:
        raise SystemExit("missing icon %06X" % src)
    px = open(files[0], "rb").read()
    ox, oy = (slot % 8) * 32, (slot // 8) * 32
    for y in range(32):
        for x in range(32):
            r, g, b, a = px[(y * 32 + x) * 4:(y * 32 + x) * 4 + 4]
            atlas[(oy + y) * W + ox + x] = (r << 24 | g << 16 | b << 8 | a) if a >= 128 else 0

out = ["// Mega Man 64 Special Items icons: 256x128 RGBA8 (0xRRGGBBAA), row-major, 32x32 icons, 8 per",
       "// row in the start menu's slot order. Generated by tools/extract_icons.py from the renderer's",
       "// texture dump of the menu (the icon sheet is only in RAM while the menu is open).",
       "#define ITEM_ICONS_W %d" % W, "#define ITEM_ICONS_H %d" % H,
       "#define ITEM_ICON_COUNT %d" % len(SLOT_SOURCES),
       "static const u32 item_icons[ITEM_ICONS_W * ITEM_ICONS_H] = {"]
for k in range(0, len(atlas), 8):
    out.append("    " + ", ".join("0x%08X" % v for v in atlas[k:k + 8]) + ",")
out.append("};")
open(ROOT + "/source/ui/item_icons.inc", "w", newline="\n").write("\n".join(out) + "\n")
print("packed", len(SLOT_SOURCES), "icons")
